/**
 * Writes examples/angular-demo/src/environments/environment.ts from CI variables
 * before the Angular demo build so the preview app has valid Sisense credentials.
 *
 * Required CI/CD variables (set as masked in Settings → CI/CD → Variables):
 *   REVIEW_APP_SISENSE_URL   — Sisense instance URL, e.g. https://my-sisense.example.com
 *   REVIEW_APP_SISENSE_TOKEN — API token for the preview user
 *
 * Usage:
 *   node ci/generate-angular-env.mjs
 */

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const sisenseUrl = process.env.REVIEW_APP_SISENSE_URL;
const sisenseToken = process.env.REVIEW_APP_SISENSE_TOKEN;

if (!sisenseUrl || !sisenseToken) {
  console.error(
    'Error: REVIEW_APP_SISENSE_URL and REVIEW_APP_SISENSE_TOKEN must be set.',
  );
  process.exit(1);
}

const envFilePath = resolve(
  rootDir,
  'examples/angular-demo/src/environments/environment.development.ts',
);

const content = `// AUTO-GENERATED by ci/generate-angular-env.mjs — do not edit manually.
export const environment = {
  APP_SISENSE_URL: ${JSON.stringify(sisenseUrl)},
  APP_SISENSE_TOKEN: ${JSON.stringify(sisenseToken)},
  APP_SSO_ENABLED: false,
  APP_WIDGETS: '',
  APP_SISENSE_THEME_OID_LIGHT: '',
  APP_SISENSE_THEME_OID_DARK: '',
  APP_ENABLE_TRACKING: true,
  APP_DISABLE_ANIMATION: false,
  APP_DISABLE_DEMO_BAR: false,
};
`;

writeFileSync(envFilePath, content, 'utf8');
console.log(`✓ Written ${envFilePath}`);
